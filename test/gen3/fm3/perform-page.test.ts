export const PERFORM_PAGE_CASE_COUNT = 7;

const failures: string[] = [];
function t(name: string, fn: () => void): void {
  try { fn(); } catch (e) { failures.push(`${name}: ${(e as Error).message}`); }
}
function eq<T>(got: T, want: T, msg: string): void {
  if (got !== want) throw new Error(`${msg}: got ${JSON.stringify(got)}, want ${JSON.stringify(want)}`);
}

export function runPerformPageTests(): void {
  failures.length = 0;

  t('the tables are found at the start of the slice', () => {
    eq(findPerformTables(PAGE), 0, 'tables offset');
  });

  const page = parsePerformPage(PAGE)!;
  t('six slots are assigned', () => { eq(page.assigned, 6, 'assigned slots'); });
  t('slot 1 is Amp 1 master volume', () => {
    eq(page.slots[0]!.effectId, 58, 'eid');
    eq(page.slots[0]!.paramId, 11, 'pid');
    eq(page.slots[0]!.effectLabel, 'AMP', 'effect label');
    eq(page.slots[0]!.paramLabel, 'Master Volume', 'param label');
  });
  t('slot 3 is Reverb pre-delay and slot 4 is the Reverb bypass toggle', () => {
    eq(page.slots[2]!.effectId, 66, 'slot 3 eid');
    eq(page.slots[2]!.paramLabel, 'Pre-Delay', 'slot 3 param label');
    eq(page.slots[3]!.paramId, 22, 'slot 4 pid — the profile id for REVERB_BYPASS');
    eq(page.slots[3]!.paramLabel, 'Bypass', 'slot 4 param label');
  });
  t('a long label is TRUNCATED by the 32-byte slot, and that is reported as-is', () => {
    eq(page.slots[4]!.paramLabel, 'Proximity Frequ', 'slot 5 is cut at the slot width — the parser must not invent the rest');
  });
  t('an unassigned slot reports eid 0 whatever stale text it carries', () => {
    eq(page.slots[6]!.effectId, 0, 'slot 7 is unassigned');
  });
  t('a body with no page yields undefined, never a candidate', () => {
    eq(parsePerformPage(new Uint8Array(200)), undefined, 'no page in a zeroed body');
  });

  if (failures.length) {
    console.error(`FAIL fm3/perform-page — ${failures.length} of ${PERFORM_PAGE_CASE_COUNT} case(s):`);
    for (const f of failures) console.error(`   ${f}`);
    process.exitCode = 1;
    return;
  }
  console.log(`PASS fm3/perform-page (${PERFORM_PAGE_CASE_COUNT} per-preset perform page cases)`);
}
